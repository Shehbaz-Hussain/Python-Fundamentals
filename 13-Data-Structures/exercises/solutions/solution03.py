# Create a tuple containing month names.
months = ("January", "February", "March", "April")

# Print the complete tuple.
print(months)

# Print the second month using index 1.
print(months[1])

# Print the last month using index -1.
print(months[-1])

# Expected Output:
# ('January', 'February', 'March', 'April')
# February
# April