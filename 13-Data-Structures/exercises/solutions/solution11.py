# Create the list.
numbers = [10, 20, 30, 40, 50]

# Create the tuple.
months = ("January", "February", "March")

# Create the set.
colors = {"Red", "Green", "Blue"}

# Create the dictionary.
student = {
    "name": "Ali",
    "age": 20,
    "grade": "A"
}

# Print each data structure.
print(numbers)
print(months)
print(colors)
print(student)

# Print the length of each data structure.
print(len(numbers))
print(len(months))
print(len(colors))
print(len(student))