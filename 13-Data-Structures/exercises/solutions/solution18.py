# Create the fruits list.
fruits = ["Apple", "Banana", "Mango"]

# Create the colors set.
colors = {"Red", "Green", "Blue"}

# Print both data structures.
print(fruits)
print(colors)

# Check whether "Mango" is in the fruits list.
print("Mango" in fruits)

# Check whether "Orange" is in the fruits list.
print("Orange" in fruits)

# Check whether "Green" is in the colors set.
print("Green" in colors)

# Check whether "Black" is not in the colors set.
print("Black" not in colors)