# Create a list of fruits.
fruits = ["Apple", "Banana", "Mango", "Orange"]

# Print the complete list.
print(fruits)

# Print the first element using index 0.
print(fruits[0])

# Print the last element using index -1.
print(fruits[-1])

# Expected Output:
# ['Apple', 'Banana', 'Mango', 'Orange']
# Apple
# Orange