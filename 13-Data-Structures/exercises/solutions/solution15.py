# Create a list named scores.
scores = [45, 78, 92, 64, 81]

# Print the complete list.
print(scores)

# Print the number of elements.
print(len(scores))

# Print the smallest value.
print(min(scores))

# Print the largest value.
print(max(scores))

# Print the sum of all values.
print(sum(scores))